import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptRoot = dirname(fileURLToPath(import.meta.url));
const modelRoot = resolve(
  scriptRoot,
  "../public/morph/animated-morph-sphere",
);
const morph = await import(pathToFileURL(
  resolve(scriptRoot, "../../packages/morph/dist/index.js"),
));
const polycss = await import(pathToFileURL(
  resolve(scriptRoot, "../../packages/polycss/dist/index.js"),
));

const model = morph.validatePolyMorphModel(JSON.parse(
  readFileSync(resolve(modelRoot, "runtime.json"), "utf8"),
));
if (
  model.identity.id !== "animated-morph-sphere"
  || model.profile !== "morph-regions"
) {
  throw new Error("Animated Morph Sphere model identity or profile drifted.");
}

const deformation = morph.createPolyMorphDeformationRuntime(model);
const blob = model.animations.find(({ id }) => id === "example-blob");
const spin = model.animations.find(({ id }) => id === "example-spin");
if (!blob || !spin) {
  throw new Error("Animated Morph Sphere clips are incomplete.");
}

const morphWeights = Object.fromEntries(
  deformation.targetIds.map((id) => [id, id === "blob" ? 1 : 0]),
);
const peak = deformation.sample({ tick: 0, morphWeights });
if (
  peak.leafUpdates.length !== 870
  || peak.leafUpdates.some((update) => !update.matrix || update.visible === false)
) {
  throw new Error("Animated Morph Sphere peak frame drifted.");
}

const multiply = (left, right) => {
  const output = new Array(16).fill(0);
  for (let column = 0; column < 4; column += 1) {
    for (let row = 0; row < 4; row += 1) {
      for (let axis = 0; axis < 4; axis += 1) {
        output[(column * 4) + row] += (
          left[(axis * 4) + row] * right[(column * 4) + axis]
        );
      }
    }
  }
  return output;
};
const matrixText = (matrix) =>
  `matrix3d(${polycss.formatMatrix3dValues(matrix)})`;
const safeId = (id) => {
  if (!/^[a-z0-9._-]+$/u.test(id)) {
    throw new Error(`Animated Morph Sphere CSS id ${id} is unsafe.`);
  }
  return id;
};
const modelSelector =
  `[data-poly-morph-model="${safeId(model.identity.id)}"]`;
const shapeId = safeId(model.render.shapes[0]?.id ?? "");
const spinName = "polycss-morph-sphere-spin";
const spinChannel = spin.channels.find(
  ({ target, targetId }) =>
    target === "shape-matrix" && targetId === shapeId,
);
if (!spinChannel || spinChannel.values.some((value) => value.length !== 16)) {
  throw new Error("Animated Morph Sphere spin channel drifted.");
}
const lines = [
  "/* Generated by website/scripts/generate-morph-sphere-playback.mjs. */",
  `@keyframes ${spinName}{`,
];

for (const [index, timeMs] of spinChannel.timesMs.entries()) {
  const percent = polycss.roundDecimal(
    timeMs * 100 / spin.durationMs,
    6,
  );
  lines.push(
    `${percent}%{transform:${matrixText(spinChannel.values[index])};}`,
  );
}
lines.push(
  "}",
  `${modelSelector} [data-poly-morph-shape="${shapeId}"]{`
    + `animation:${spinName} ${spin.durationMs}ms steps(1,end) infinite;}`,
);

const leafById = new Map(model.render.leaves.map((leaf) => [leaf.id, leaf]));
for (const [index, update] of peak.leafUpdates.entries()) {
  const leaf = leafById.get(update.leafId);
  if (!leaf || !update.matrix) {
    throw new Error(`Animated Morph Sphere leaf ${update.leafId} is incomplete.`);
  }
  const leafId = safeId(leaf.id);
  const selector = `${modelSelector} [data-poly-morph-leaf="${leafId}"]`;
  const animationName = `polycss-morph-sphere-blob-${index}`;
  lines.push(
    `@keyframes ${animationName}{50%{transform:${matrixText(update.matrix)};}}`,
    `${selector}{animation:${animationName} ${blob.durationMs}ms linear infinite;}`,
  );
  if (leaf.fallback) {
    const fallbackAnimationName = `${animationName}-fallback`;
    lines.push(
      `@keyframes ${fallbackAnimationName}{50%{transform:${matrixText(multiply(
        update.matrix,
        leaf.fallback.matrixFromLeaf,
      ))};}}`,
      `${selector}[data-poly-morph-resolved-strategy="atlas-slice"]{`
        + `animation-name:${fallbackAnimationName};}`,
    );
  }
}

writeFileSync(
  resolve(modelRoot, "playback.css"),
  `${lines.join("\n")}\n`,
);
